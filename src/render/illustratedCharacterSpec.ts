import type { Person } from '../sim/types';
import {
  resolveCharacterWardrobe, type ResolvedCharacterWardrobe,
  type WardrobePerson,
} from './characterWardrobe';

/**
 * Artwork-independent blueprint for the *next* illustrated character renderer.
 *
 * This does not create or claim to provide painted parts: the current
 * IllustratedPeople atlas continues drawing the game. Artists/build tooling
 * will provide separate directional layer atlases against this specification.
 */
export const ILLUSTRATED_2D_DIRECTIONS = ['front', 'back', 'left', 'right'] as const;
export type IllustratedDirection = typeof ILLUSTRATED_2D_DIRECTIONS[number];
export const ILLUSTRATED_2D_WALK_FRAMES = 4;

/**
 * Global front-to-back order for a person. A character is drawn in one anchor
 * space; costume cuts must align with body shape, pose and foot contact.
 */
export const ILLUSTRATED_2D_LAYER_ORDER = [
  'backHair', 'bodyLower', 'clothesLower', 'bodyUpper', 'clothesUpper',
  'face', 'frontHair', 'headwear',
] as const;
export type IllustratedLayerSlot = typeof ILLUSTRATED_2D_LAYER_ORDER[number];

export interface IllustratedLayerSpec {
  slot: IllustratedLayerSlot;
  /** Logical asset identity, not a URL or a claim that art exists yet. */
  key: string;
  /** RGB tint applied at draw time, without creating a texture per citizen. */
  tint: number;
}

export interface IllustratedCharacterSpec {
  /**
   * May be shared between people with identical wardrobes; IDs do not force
   * individual GPU textures. No extra field is added to saved Person records.
   */
  appearanceKey: string;
  sex: 'male' | 'female';
  bodyId: string;
  heightScale: number;
  faceId: string;
  skinColor: number;
  hairId: string;
  headwearId: string;
  outfitId: string;
  layers: readonly IllustratedLayerSpec[];
}

/** Pure specification mapping. Future layered art is *not* enabled by this. */
export function illustratedCharacterSpec(
  person: WardrobePerson,
  resolved: ResolvedCharacterWardrobe = resolveCharacterWardrobe(person),
): IllustratedCharacterSpec {
  const w = resolved;
  const sex = person.female ? 'female' : 'male';
  const id = w.body.id;
  const base: IllustratedLayerSpec[] = [
    { slot: 'backHair', key: `hair/${w.hair.id}/back`, tint: w.hair.color },
    { slot: 'bodyLower', key: `body/${id}/lower`, tint: w.skinColor },
    { slot: 'clothesLower', key: `outfit/${w.outfit.id}/lower`, tint: w.outfit.trousersColor },
    { slot: 'bodyUpper', key: `body/${id}/upper`, tint: w.skinColor },
    { slot: 'clothesUpper', key: `outfit/${w.outfit.id}/upper`, tint: w.outfit.coatColor },
    { slot: 'face', key: `face/${w.face.id}`, tint: w.skinColor },
    { slot: 'frontHair', key: `hair/${w.hair.id}/front`, tint: w.hair.color },
  ];
  if (w.headwear.kind !== 'none') base.push({
    slot: 'headwear', key: `headwear/${w.headwear.id}`, tint: w.headwear.color,
  });
  const layerOrder = new Map<IllustratedLayerSlot, number>(
    ILLUSTRATED_2D_LAYER_ORDER.map((slot, index) => [slot, index]),
  );
  base.sort((a, b) => layerOrder.get(a.slot)! - layerOrder.get(b.slot)!);
  return {
    appearanceKey: `${sex}:${w.signature}`,
    sex, bodyId: id, heightScale: w.heightScale,
    faceId: w.face.id, skinColor: w.skinColor, hairId: w.hair.id,
    headwearId: w.headwear.id, outfitId: w.outfit.id, layers: base,
  };
}

/**
 * Produces a *logical* atlas lookup. Build-time art compiler will map logical
 * keys to UV rectangles; no image files are generated by this function.
 */
export function illustratedLayerTile(
  layer: IllustratedLayerSpec,
  direction: IllustratedDirection,
  frame: number,
): string {
  if (!ILLUSTRATED_2D_DIRECTIONS.includes(direction)) throw Error('Unknown illustrated direction');
  if (!Number.isInteger(frame) || frame < 0 || frame >= ILLUSTRATED_2D_WALK_FRAMES)
    throw Error('Illustrated walk frame out of range');
  return `${layer.key}/${direction}/${frame}`;
}

export function sameIllustratedIdentity(a: Pick<Person, 'id' | 'portrait'>,
  b: Pick<Person, 'id' | 'portrait'>): boolean {
  return a.id === b.id && a.portrait === b.portrait;
}
